METADATA_EXTRACTION_PROMPT = """请从以下财经文本中提取元数据，以 JSON 格式返回：

文本内容：
{text}

需要提取的字段：
- source: 信息来源（如"上交所公告"、"央行公告"、"财经媒体"等）
- company: 涉及的主要公司名称（全称）
- date: 文本中提及的日期或发布日期（YYYY-MM-DD）
- fiscal_period: 财报期间（如"2024年度"、"2024Q1"），非财报则留空
- currency: 货币单位（如"CNY"、"USD"），默认 CNY
- doc_type: 文档类型，从以下选择：年报、季报、公告、政策文件、新闻报道、研究报告、其他

仅返回一个合法的 JSON 对象，不要添加任何其他文字。"""


# ===================== 财务指标抽取 =====================

FINANCIAL_METRICS_EXTRACTION_SYSTEM = """你是一位专业的财务分析师，擅长从财报文本中精确抽取结构化财务指标。

核心原则：
1. 只提取文本中明确给出的数值，绝不编造或推测
2. 数字保留原始精度，包括单位（如"亿元"、"万元"）
3. 同时提取数值和对应的增长率（如有）
4. 区分"合并报表"和"母公司报表"数据（默认取合并报表）
5. 如果某项指标未在文本中出现，不要包含该字段
6. 严格按照 JSON 格式输出，不要添加任何额外的解释文字"""

FINANCIAL_METRICS_EXTRACTION_PROMPT = """请从以下文本中提取所有可识别的财务指标，以 JSON 格式返回：

文本内容：
{text}

需要关注的关键指标（如文本中存在则提取）：
- revenue: 营业收入（含同比增长率）
- net_income: 归属净利润（含同比增长率）
- gross_margin: 毛利率
- operating_cash_flow: 经营活动现金流量净额（含同比变化率）
- total_assets: 总资产
- total_liabilities: 总负债
- asset_liability_ratio: 资产负债率
- eps: 基本每股收益（含同比增长率）
- roe: 净资产收益率
- 其他可识别的财务数据（如分产品营收、产能数据等）

对于每个指标，格式为：
{{
  "value": 数值(数字),
  "unit": "单位(如亿元、%、元)",
  "yoy_growth": "同比增长率(字符串，如+15.66%或无)",
  "period": "所属期间"
}}

仅返回一个合法的 JSON 对象。"""


# ===================== 实体抽取 =====================

ENTITY_EXTRACTION_SYSTEM = """你是一位金融实体识别专家，擅长从财经新闻中抽取关键实体和事件信息。

实体类别：
1. 公司/机构：涉及的企业、政府机构、监管机构
2. 人物：提及的关键人物及其职务
3. 金融指标：文中出现的具体数字和指标
4. 事件类型：并购、分红、政策发布、财报发布、融资、人事变动等
5. 行业/板块：涉及的行业或市场板块

规则：
- 只提取文本中明确提及的实体
- 每个实体附带其在文中的简要上下文
- 事件需标注影响范围（正面/负面/中性）
- 严格按照 JSON 格式输出"""

ENTITY_EXTRACTION_PROMPT = """请从以下财经文本中抽取结构化实体信息，以 JSON 格式返回：

文本内容：
{text}

需要抽取的实体类别：
1. "companies": 涉及的公司/机构列表，每项包含 name、role（角色）、industry
2. "persons": 关键人物列表，每项包含 name、title（职务）
3. "financial_figures": 关键数字列表，每项包含 label（含义）、value、unit
4. "event": 核心事件，包含 type（事件类型）、description（简要描述）、impact（正面/负面/中性）
5. "related_companies": 受影响的关联公司列表
6. "industries": 涉及的行业/板块列表
7. "key_topics": 关键主题词列表（3-5个）

仅返回一个合法的 JSON 对象，不要添加任何其他文字。"""


